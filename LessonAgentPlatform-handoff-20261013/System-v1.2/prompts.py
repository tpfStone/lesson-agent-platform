# 两套评分维度体系（维度名, 满分）
COMPETITION_DIMS = [
    ("教学内容", 10), ("教学理念", 5), ("学情分析", 5), ("教学目标", 5),
    ("教学资源", 10), ("教学方法", 10), ("过程设计", 20), ("课程思政", 5),
    ("课堂互动", 10), ("评价反馈", 10), ("版式观感", 5), ("文档规范", 5),
]

STUDENT_DIMS = [
    ("教学理念", 5), ("课程思政", 5), ("学情分析", 5), ("教学目标", 5),
    ("教学内容", 10), ("教学资源", 10), ("教学方法", 10), ("过程设计", 20),
    ("课堂互动", 10), ("评价反馈", 10), ("版式观感", 5), ("结构完整", 5),
]

DIMS_BY_CRITERIA = {
    "competition": COMPETITION_DIMS,
    "student": STUDENT_DIMS,
}


def build_output_format(dims) -> str:
    """
    按维度体系动态生成输出格式约束 JSON 模板。
    dims: [(维度名, 满分), ...]
    """
    dim_lines = ",\n    ".join(
        '{"维度名称":"%s","满分":%d,"得分":0,"得分理由":"","批注列表":'
        '[{"位置":"","原文引用":"","具体分析":"","建议":""}]}'
        % (name, score) for name, score in dims
    )
    scores = ", ".join('"%s":0' % name for name, _ in dims)

    return f"""## 输出格式要求

你必须严格按照以下 JSON 格式输出。维度名称和满分已固定，不得修改。
（批注无需输出等级字段——系统会按维度得分自动标注 A/B/C 等级）

```json
{{
  "教案基本信息": {{
    "课题名称": "从教案中提取",
    "学科": "从教案中提取",
    "年级": "从教案中提取",
    "课型": "从教案中提取"
  }},
  "总体评价": "200字以内的总体评价",
  "维度评分": [
    {dim_lines}
  ],
  "评分汇总": {{
    "总分": 0,
    "各维度得分": {{{scores}}}
  }}
}}
```

重要提醒：
1. 只输出 JSON，不要加任何解释
2. 批注无需"评价/等级"字段（系统会按维度得分自动标注 A/B/C），请勿自创等级字段
3. 必须包含全部 {len(dims)} 个维度，满分值不可修改
4. 每个维度至少2条、最多4条批注（控制输出长度，避免截断）
5. 总分 = 各维度得分之和
6. 每条批注的"建议"字段 = 纯诊断：1-2 句话点明该条批注揭示的核心问题或缺失，
   禁止写修改方法（如"建议改为…""可增加…"）。示例："目标使用'了解'等模糊动词，无法判断达成度。"
"""

# 兼容旧引用：默认（竞赛标准）输出格式
OUTPUT_FORMAT = build_output_format(COMPETITION_DIMS)


# ============================================================
# 主提示词构建
# ============================================================

def build_user_prompt(
    examples: List[Dict],
    criteria_text: str,
    criteria_name: str,
    plan_text: str,
    plan_filename: str,
    max_examples: int = 2,
    dim_names: List[str] = None,
    standards_text: str = "",
    dims: List[tuple] = None,
    anchor_text: str = "",
) -> str:
    """
    组装完整的 user prompt。

    参数:
      dim_names: 评分标准的维度名列表（兼容旧接口，已由 dims 取代）
      dims: [(维度名, 满分), ...]，决定输出格式的维度体系；
            为 None 时按 criteria_name 选择（competition/student），否则用竞赛标准
      anchor_text: 维度档位锚点参照（粗评归纳），用于校准打分尺度
    """
    if dims is None:
        dims = DIMS_BY_CRITERIA.get(criteria_name, COMPETITION_DIMS)
    output_format = build_output_format(dims)
    prompt = ""

    # === 第一部分：标注示例 ===
    examples_to_use = examples[:max_examples]
    if examples_to_use:
        prompt += f"## 学习材料：{len(examples_to_use)} 份标注示例\n\n"
        prompt += "请仔细学习以下标注示例，理解其标注思路、评语风格和评分逻辑。\n"
        prompt += "注意：示例教案可能与你将要评价的教案来自不同学科或年级，"
        prompt += '重点学习的是「如何评价」的方法论，而不是照搬具体评语。\n\n'

        for i, ex in enumerate(examples_to_use, 1):
            prompt += format_example(ex, i)
            prompt += "\n"

        prompt += "---\n\n"

    # === 第二部分：评分标准 ===
    prompt += f"## 评分标准：{criteria_name}\n\n"
    prompt += criteria_text
    prompt += "\n\n---\n\n"

    # === 第三部分：待评价教案 ===
    prompt += f"## 待评价教案：{plan_filename}\n\n"
    prompt += plan_text
    prompt += "\n\n---\n\n"

    # === 第四部分：课标对照 ===
    if standards_text:
        prompt += standards_text
        prompt += "\n"

    # === 第四部分之二：维度档位锚点（粗评归纳，用于校准打分尺度）===
    if anchor_text:
        prompt += anchor_text
        prompt += "\n---\n\n"

    # === 第五部分：输出格式 ===
    prompt += output_format

    return prompt


