from typing import Dict, List


# ============================================================
# 系统提示词
# ============================================================

SYSTEM_PROMPT = """你是一位资深的教育学评价专家，专门从事教学设计的专业评审工作。

## 你的任务
你将看到几份"已标注的教案示例"和一份"待评价的新教案"。
你需要先学习示例中的标注思路、评语风格和评分逻辑，然后用同样的方式对新教案进行批注和评分。

## 工作原则
1. **学思路，不抄内容**：示例教案和新教案可能来自不同学科、不同年级。
   重点是学习"评什么人用什么话、从什么角度切入、证据怎么引用"，而不是照搬具体评语。
2. **逐条对照评分标准**：每一条判断都要在教案中找到对应的原文证据。
3. **批注有建设性**：不只说"对"或"错"，要指出具体怎么改进。
4. **无需输出等级**：批注不需要你给出"评价等级"。系统会依据该维度的最终得分，
   按评价标准的 A / B / C 区间自动标注等级。你只需专注：把问题说清楚、把原文证据引准确。
5. **评分有区分度**：不同教案应给出不同分数，敢于指出问题。
6. **语言风格一致**：模仿示例中的语气（专业而不生硬，肯定优点也直指不足）。
6. **跨维度不重复扣分**：如果同一段原文在多个维度被引用（如"云平台"同时出现在教学资源和评价反馈中），
   必须在每条批注中明确说明「本维度关注的侧重点是什么，与其他维度的区别在哪里」。
   例如：教学资源维度关注的是"有没有用"，评价反馈维度关注的是"用了之后效果如何"。
   不允许两条批注的分析文字雷同。
7. **"建议"字段 = 纯诊断**：每条批注的"建议"只输出诊断结论，用 1-2 句话直接点明
   该条批注揭示的核心问题或缺失，不写修改方法、不写解决方案。
   例：「教学目标使用'了解''掌握'等模糊动词，无法判断学生达成度。」
   修改方法由后续流程另行生成，本字段一律不涉及"怎么改"。

## 评分维度（必须全部使用，不得增减改名）
1. 教学内容（10分）— 教材分析、知识前后联系、重难点把握
2. 教学理念（5分）— 核心素养、课标理念、数字技术融合
3. 学情分析（5分）— 学生认知水平、知识基础、学习困难
4. 教学目标（5分）— 目标定位、表述准确性、可测评性
5. 教学资源（10分）— 资源选用、数字技术应用、创新性
6. 教学方法（10分）— 方法适配性、自主学习、合作探究
7. 过程设计（20分）— 环节完整性、逻辑清晰度、时间安排
8. 课程思政（5分）— 思政元素挖掘、融合方式、持续性
9. 课堂互动（10分）— 互动形式、学生参与度、数字技术互动
10. 评价反馈（10分）— 评价方式、教学评一致性、反馈精准度
11. 版式观感（5分）— 布局合理性、图文搭配、可读性
12. 文档规范（5分）— 结构完整性、格式规范性、要素齐全

## 输出要求
严格按照指定的 JSON 格式输出，不要添加额外解释文字。"""


# ============================================================
# Few-Shot 示例格式化
# ============================================================

def format_example(example: Dict, index: int) -> str:
    """
    将一个标注示例格式化为提示词中的演示块。

    支持两种标注格式：
    1. JSON 结构（annotation_type="json"）：结构化展示评分和批注
    2. 纯文本（annotation_type="text"）：直接嵌入标注全文

    返回：格式化的示例文本块
    """
    ann = example["annotation"]
    ann_type = example.get("annotation_type", "json")

    text = f"""\n{'='*50}
【标注示例 {index}】
{'='*50}\n"""

    # --- 原始教案（摘要）---
    text += f"\n## 原始教案（摘要）\n{_truncate_plan(example['plan_text'])}\n"

    # --- 标注结果 ---
    if ann_type == "json":
        text += _format_json_annotation(ann)
    else:
        text += f"\n## 标注结果\n\n{ann}\n"

    text += "\n" + "=" * 50 + "\n"
    return text


def _format_json_annotation(ann: Dict) -> str:
    """格式化 JSON 结构的标注结果"""
    info = ann.get("教案基本信息", {})
    summary = ann.get("评分汇总", {})
    overall = ann.get("总体评价", "")

    text = f"""
## 评分结果与批注

课题：{info.get('课题名称', '未知')} | 学科：{info.get('学科', '未知')} | 年级：{info.get('年级', '未知')}
总分：{summary.get('总分', '?')}/100

### 总体评价
{overall}

### 各维度评分与批注
"""

    for dim in ann.get("维度评分", []):
        text += f"""
---
### {dim.get('维度名称', '')}：{dim.get('得分', 0)}/{dim.get('满分', 0)}分
理由：{dim.get('得分理由', '')}

"""
        for ann_item in dim.get("批注列表", []):
            text += f"""- **位置**：{ann_item.get('位置', '')}
  **原文**：「{ann_item.get('原文引用', '')}」
  **评价**：{ann_item.get('评价', '')}
  **分析**：{ann_item.get('具体分析', '')}
"""
            sug = ann_item.get('建议', '') or ann_item.get('改进建议', '')
            if sug and sug != '无需改进':
                text += f"  **建议**：{sug}\n"

    return text


def _truncate_plan(plan_text: str, max_chars: int = 1500) -> str:
    """截断教案文本，节省 token"""
    if len(plan_text) <= max_chars:
        return plan_text
    # 取前 1000 + 后 500 字符
    half = max_chars // 2
    return plan_text[:half] + f"\n\n... [中间省略 {len(plan_text) - max_chars} 字符] ...\n\n" + plan_text[-half:]


