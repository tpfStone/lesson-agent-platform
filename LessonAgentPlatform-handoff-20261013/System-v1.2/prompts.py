def get_prompt_variant(variant: str = "default") -> Dict:
    """获取指定变体的 system prompt"""
    variants = {
        "default": SYSTEM_PROMPT,
        "v2_guided": SYSTEM_PROMPT_V2,
        "v3_strict": SYSTEM_PROMPT_V3_STRICT,
    }
    return {"system": variants.get(variant, SYSTEM_PROMPT)}
